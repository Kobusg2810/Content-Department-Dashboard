/**
 * Get GID for a qualification by name
 * @param {string} qualName - Qualification name
 * @returns {string|null} GID or null if not found
 */
export function getQualificationGID(qualName) {
    const normalized = qualName.toUpperCase().trim();
    const gid = QUALIFICATION_GIDS[normalized];

    // Debug logging
    if (!gid) {
        console.log(`⚠️ No GID found for: "${normalized}"`);
    } else {
        console.log(`✅ GID found for: "${normalized}" -> ${gid}`);
    }

    return gid || null;
}
